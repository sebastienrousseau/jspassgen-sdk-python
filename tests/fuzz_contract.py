"""The contract of ``SecretsRandom``, checked on arbitrary input bytes.

``check(data)`` decodes ``data`` into a call and asserts what the public
API promises for it. The Atheris harness (``fuzz/fuzz_random.py``) feeds
it coverage-guided input; ``tests/test_fuzz.py`` replays the committed
seed corpus and Hypothesis-generated bytes through it, so the same
properties run in the unit tests on every platform, Atheris or not.

The first byte picks the target and the argument's type; the rest is the
argument:

- ``random_int(max)``: an ``int`` of at least 1 gives an ``int`` in
  ``[0, max)``; below 1 raises ``ValueError``; any other type, ``bool``
  included, raises ``TypeError``. Messages name the argument only.
- ``random_bytes(n)``: ``n`` bytes, with the same errors.
- ``_below(max, randbits)``, the rejection loop, with ``randbits``
  replaying candidates from the input: every draw asks for the bit
  length of ``max - 1``, and the result is the first candidate below
  ``max``, never a reduction of one that is not.
"""

from __future__ import annotations

import re
from collections.abc import Callable, Iterator
from typing import Any

import pytest

from jspassgen import SecretsRandom
from jspassgen.adapters import _below

RNG = SecretsRandom()

#: ``random_bytes`` is not asked for more than this, to bound memory.
MAX_BYTES = 4096
#: The longest ``max`` the rejection-loop check decodes, in bytes.
MAX_WIDTH = 16
#: Selector values: ``head % 3`` picks the target.
RANDOM_INT, RANDOM_BYTES, BELOW = range(3)
#: ``head // 3 % KINDS`` picks the argument: 0 to 3 an int (half the
#: input), 4 to 7 a float, str, bool and bytes.
KINDS = 8


def _arguments(raw: bytes) -> list[object]:
    """The argument forms a selector can pick: an int, then non-ints."""
    value = int.from_bytes(raw, "big", signed=True)
    return [value, float(value), str(value), value > 0, raw]


def _expect_error(call: Callable[[Any], object], arg: object, name: str) -> None:
    """``call(arg)`` must raise the error the API documents for ``arg``."""
    if isinstance(arg, int) and not isinstance(arg, bool):
        error: type[Exception] = ValueError
        message = f"{name} must be a positive integer"
    else:
        error, message = TypeError, f"{name} must be an int"
    with pytest.raises(error, match=f"^{re.escape(message)}$"):
        call(arg)


def _check_random_int(arg: object) -> None:
    if type(arg) is int and arg >= 1:
        out = RNG.random_int(arg)
        assert type(out) is int
        assert 0 <= out < arg
    else:
        _expect_error(RNG.random_int, arg, "max")


def _check_random_bytes(arg: object) -> None:
    if type(arg) is int and arg >= 1:
        if arg <= MAX_BYTES:
            out = RNG.random_bytes(arg)
            assert type(out) is bytes
            assert len(out) == arg
    else:
        _expect_error(RNG.random_bytes, arg, "n")


def _candidates(data: bytes, bits: int) -> list[int]:
    """Split ``data`` into ``bits``-wide draws, as ``randbits`` returns them."""
    width = max(1, (bits + 7) // 8)
    mask = (1 << bits) - 1
    return [
        int.from_bytes(data[i : i + width], "big") & mask
        for i in range(0, len(data) - width + 1, width)
    ]


def _check_below(data: bytes) -> None:
    width = 1 + data[0] % MAX_WIDTH if data else 1
    max_ = int.from_bytes(data[1 : 1 + width], "big") + 1
    bits = (max_ - 1).bit_length()
    draws = _candidates(data[1 + width :], bits)
    # Once the input runs out, randbits returns 0, which is always in range.
    feed: Iterator[int] = iter([*draws, 0])
    calls: list[int] = []

    def randbits(k: int) -> int:
        calls.append(k)
        return next(feed)

    out = _below(max_, randbits)
    expected = next((d for d in draws if d < max_), 0)
    assert out == expected
    assert 0 <= out < max_
    assert calls == [bits] * len(calls)
    assert len(calls) == next((i + 1 for i, d in enumerate(draws) if d < max_), len(draws) + 1)


def check(data: bytes) -> None:
    """Decode ``data`` into one call and assert the API's contract for it."""
    if not data:
        return
    head, rest = data[0], data[1:]
    target = head % 3
    if target == BELOW:
        _check_below(rest)
        return
    forms = _arguments(rest[:MAX_WIDTH])
    arg = forms[max(0, head // 3 % KINDS - 3)]
    if target == RANDOM_INT:
        _check_random_int(arg)
    else:
        _check_random_bytes(arg)
